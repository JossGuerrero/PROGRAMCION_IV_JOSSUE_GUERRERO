fun main() {
    println("Operadores de Comparación en control de vuelos")

    val vuelo1 = 15
    val vuelo2 = 10

    println("$vuelo1 == $vuelo2 = ${vuelo1 == vuelo2}")
    println("$vuelo1 .equals $vuelo2 = ${vuelo1.equals(vuelo2)}")
    println("$vuelo1 != $vuelo2 = ${vuelo1 != vuelo2}")
    println("$vuelo1 > $vuelo2 = ${vuelo1 > vuelo2}")
    println("$vuelo1 >= $vuelo2 = ${vuelo1 >= vuelo2}")
    println("$vuelo1 < $vuelo2 = ${vuelo1 < vuelo2}")
    println("$vuelo1 <= $vuelo2 = ${vuelo1 <= vuelo2}")
}